"""Models for the deterministic auto-fix, tailoring and change-review API.

Every proposed edit is represented by a :class:`ResumeChange` that keeps a
traceable reference to the original text, an explanation, a fabrication-guard
verdict and a review status. Nothing here is generated by an external model.
"""

from __future__ import annotations

from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, field_validator

from .analysis import AnalysisResponse
from .structured import SourceLine

MIN_JOB_DESCRIPTION_CHARS = 30
MAX_JOB_DESCRIPTION_CHARS = 20_000


class ChangeCategory(str, Enum):
    HEADING_NORMALIZATION = "heading_normalization"
    DATE_NORMALIZATION = "date_normalization"
    BULLET_NORMALIZATION = "bullet_normalization"
    DUPLICATE_SKILLS = "duplicate_skills"
    SKILL_GROUPING = "skill_grouping"
    SKILL_ORDERING = "skill_ordering"
    FIRST_PERSON = "first_person"
    WEAK_OPENER = "weak_opener"
    TENSE_NORMALIZATION = "tense_normalization"
    BULLET_SHORTENING = "bullet_shortening"
    BULLET_REWRITE = "bullet_rewrite"
    MISSING_CONTACT = "missing_contact"
    MISSING_SECTION = "missing_section"
    PERSONAL_DETAIL = "personal_detail"


class ChangeAction(str, Enum):
    """Whether a change rewrites text or is an advisory flag."""

    REPLACE = "replace"
    FLAG = "flag"


class ChangeStatus(str, Enum):
    PROPOSED = "proposed"
    ACCEPTED = "accepted"
    REJECTED = "rejected"


class GuardStatus(str, Enum):
    """Fabrication-guard verdict for a proposed change."""

    SAFE = "safe"
    NEEDS_REVIEW = "needs_review"
    UNSAFE = "unsafe"


class ChangeOrigin(str, Enum):
    AUTOFIX = "autofix"
    TAILOR = "tailor"


class ResumeChange(BaseModel):
    """A single, explainable proposed edit to a resume."""

    model_config = ConfigDict(extra="forbid")

    id: str = Field(..., description="Stable identifier derived from the change content.")
    category: ChangeCategory
    action: ChangeAction = ChangeAction.REPLACE
    origin: ChangeOrigin = ChangeOrigin.AUTOFIX
    title: str
    original_text: str = ""
    proposed_text: str | None = None
    reason: str
    source_line: int | None = Field(default=None, ge=1)
    source_end_line: int | None = Field(
        default=None,
        ge=1,
        description="Last physical line the change replaces; None means a single line.",
    )
    evidence: list[SourceLine] = Field(default_factory=list)
    guard_status: GuardStatus = GuardStatus.SAFE
    guard_reasons: list[str] = Field(default_factory=list)
    status: ChangeStatus = ChangeStatus.PROPOSED
    applicable: bool = True
    user_edited: bool = Field(
        default=False,
        description="True once the user has edited the proposed replacement text.",
    )


class ChangeSummary(BaseModel):
    model_config = ConfigDict(extra="forbid")

    total: int = 0
    proposed: int = 0
    accepted: int = 0
    rejected: int = 0
    safe: int = 0
    needs_review: int = 0
    unsafe: int = 0


class ChangeListResponse(BaseModel):
    """Response for ``GET /api/v1/resumes/{resume_id}/changes``."""

    model_config = ConfigDict(extra="forbid")

    resume_id: str
    summary: ChangeSummary
    changes: list[ResumeChange] = Field(default_factory=list)
    effective_analysis: AnalysisResponse


class ChangeDecisionResponse(BaseModel):
    """Response for accepting or rejecting a single change."""

    model_config = ConfigDict(extra="forbid")

    resume_id: str
    change: ResumeChange
    applied: bool
    effective_analysis: AnalysisResponse


class ChangeEditRequest(BaseModel):
    """Request body for editing the replacement text of a proposed change."""

    model_config = ConfigDict(extra="forbid")

    proposed_text: str = Field(
        ...,
        description="The user-supplied replacement text for this change.",
    )

    @field_validator("proposed_text")
    @classmethod
    def _validate(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("The replacement text cannot be empty.")
        return value


class TailorRequest(BaseModel):
    """Request body for ``POST /api/v1/resumes/{resume_id}/tailor``."""

    model_config = ConfigDict(extra="forbid")

    job_description: str = Field(..., description="The target job description text.")

    @field_validator("job_description")
    @classmethod
    def _validate_length(cls, value: str) -> str:
        stripped = value.strip()
        if len(stripped) < MIN_JOB_DESCRIPTION_CHARS:
            raise ValueError(
                f"Job description must contain at least {MIN_JOB_DESCRIPTION_CHARS} "
                "non-whitespace characters."
            )
        if len(value) > MAX_JOB_DESCRIPTION_CHARS:
            raise ValueError(
                f"Job description must be at most {MAX_JOB_DESCRIPTION_CHARS} characters."
            )
        return value


class KeywordMatch(BaseModel):
    """A job-description term and whether it appears in the resume."""

    model_config = ConfigDict(extra="forbid")

    term: str
    canonical: str
    occurrences_in_job: int = 0
    in_resume: bool = False
    evidence: list[SourceLine] = Field(default_factory=list)


class JobDescriptionStats(BaseModel):
    model_config = ConfigDict(extra="forbid")

    character_count: int
    word_count: int
    unique_terms: int


class TailorResponse(BaseModel):
    """Response for the job-description tailoring endpoint."""

    model_config = ConfigDict(extra="forbid")

    resume_id: str
    job_description_stats: JobDescriptionStats
    matched_skills: list[KeywordMatch] = Field(default_factory=list)
    missing_skills: list[KeywordMatch] = Field(default_factory=list)
    matched_keywords: list[KeywordMatch] = Field(default_factory=list)
    missing_keywords: list[KeywordMatch] = Field(default_factory=list)
    evidence_backed_skills: list[KeywordMatch] = Field(default_factory=list)
    suggested_skill_order: list[str] = Field(default_factory=list)
    bullet_suggestions: list[ResumeChange] = Field(default_factory=list)
    explanations: list[str] = Field(default_factory=list)
    match_percentage: float = Field(
        default=0.0,
        ge=0.0,
        le=100.0,
        description=(
            "Transparent term-coverage percentage: how much of the job description's "
            "recognised skills and keywords already appear in the resume."
        ),
    )
    match_note: str = Field(
        default="",
        description="Human-readable explanation of how match_percentage was computed.",
    )
    changes: ChangeListResponse

    @property
    def missing_skill_names(self) -> list[str]:
        return [match.term for match in self.missing_skills]


